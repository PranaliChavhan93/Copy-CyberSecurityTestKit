User = get_user_model()

@receiver(post_save, sender=User)
def create_totp_secret(sender, instance, created, **kwargs):
    if created and not instance.totp_secret:
        instance.totp_secret = pyotp.random_base32()
        instance.save(update_fields=["totp_secret"])

@receiver(post_save, sender=User)
def create_user_session(sender, instance, created, **kwargs):
    if created:
        UserSession.objects.create(
            user=instance,
            ip_address="0.0.0.0",
            device="system"
        )

@receiver(post_migrate)
def create_default_users(sender, **kwargs):

    if sender.name != "account":
        return

    default_users = [
        ("admin", "ADMIN", "admin123", "System", "Admin"),
        ("testmanager", "TEST_MANAGER", "testmanager123", "Test", "Manager"),
        ("tester", "TESTER", "tester123", "Test", "User"),
        ("customer", "CUSTOMER", "customer123", "Customer", "User"),
        ("master", "MASTER", "master123", "Master", "User"),
    ]

    for username, role, password, fn, ln in default_users:
        if not User.objects.filter(username=username).exists():

            user = User.objects.create_user(
                username=username,
                email=f"{username}@gmail.com",
                password=password,
                role=role,
                first_name=fn,
                last_name=ln,
                account_status="ACTIVE",
            )
            user.save()

